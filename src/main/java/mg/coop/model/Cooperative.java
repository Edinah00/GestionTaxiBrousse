package mg.coop.model;

public class Cooperative {

    private int id;
    private String nom;

    public Cooperative() {}

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNom() {
        return nom;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }
}
